//! 外部 shell 集成：给 pwsh / powershell / cmd 注入提示符脚本，让终端收到 OSC 7 与 OSC 133。
//!
//! 脚本按需写到 `%LOCALAPPDATA%\scterm\integration\`，启动窗格时通过命令行参数加载；
//! 不修改用户的 PowerShell $PROFILE，也不改注册表。

use std::path::{Path, PathBuf};

use crate::config::Profile;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ShellKind {
    PowerShell,
    Cmd,
}

/// PowerShell 集成脚本（内部注释保持 ASCII，Windows PowerShell 5.1 无 BOM 时也能正常解析）。
///
/// 包裹用户原有的 `prompt` 函数：每次显示提示符时先报告上一条命令的退出码（OSC 133;D）
/// 与当前目录（OSC 7），再输出提示符原文，并标记提示符位置（OSC 133;A）。
/// 不输出 133;B：本终端不依赖它，且能避免 PSReadLine 把转义序列计入提示符宽度。
pub const PS1_SCRIPT: &str = r#"# scterm shell integration: OSC 7 (cwd) + OSC 133 (prompt marks).
# Generated by scterm; manual edits are overwritten.
if ($global:__scterm_integration_loaded) { return }
$global:__scterm_integration_loaded = $true
if (-not (Test-Path Function:\prompt)) { return }
$global:__scterm_original_prompt = $function:prompt
$global:__scterm_esc = [char]27
$global:__scterm_bel = [char]7
function global:prompt {
    $code = $global:LASTEXITCODE
    if ($null -eq $code) { $code = 0 }
    $location = Get-Location
    $path = $location.ProviderPath
    if ([string]::IsNullOrEmpty($path)) { $path = $location.ToString() }
    $uri = ($path -replace '\\', '/') -replace '%', '%25'
    $esc = $global:__scterm_esc
    $bel = $global:__scterm_bel
    $mark = "$esc]133;D;$code$bel$esc]7;file://$env:COMPUTERNAME/$uri$bel$esc]133;A$bel"
    $text = & $global:__scterm_original_prompt
    if ($null -eq $text) { $text = "PS $path> " }
    return "$mark$text"
}
"#;

/// cmd 集成脚本：用 PROMPT 的 `$E`（ESC）输出 OSC 133;A / B 标记。
/// cmd 的提示符无法把 `%CD%` 转成 OSC 7 的 file:// 形式，也没有命令结束钩子，故不做目录与退出码。
pub const CMD_SCRIPT: &str = r#"@echo off
rem scterm shell integration: mark prompts for jump (OSC 133;A/B).
prompt $E]133;A$E\$P$G$E]133;B$E\$S
"#;

/// 识别需要集成脚本的外部 shell（`scterm.exe` 等自研程序返回 `None`）。
pub fn detect(command: &str) -> Option<ShellKind> {
    let command = command.trim().trim_matches('"');
    let name = command
        .rsplit(|c| c == '\\' || c == '/')
        .next()
        .unwrap_or(command)
        .trim_matches('"')
        .to_ascii_lowercase();
    match name.as_str() {
        "pwsh.exe" | "powershell.exe" => Some(ShellKind::PowerShell),
        "cmd.exe" => Some(ShellKind::Cmd),
        _ => None,
    }
}

/// 集成脚本目录：`%LOCALAPPDATA%\scterm\integration`（无 LOCALAPPDATA 时退回临时目录）。
pub fn dir() -> PathBuf {
    let base = std::env::var_os("LOCALAPPDATA")
        .map(PathBuf::from)
        .unwrap_or_else(std::env::temp_dir);
    base.join("scterm").join("integration")
}

#[derive(Debug, Clone)]
pub struct Assets {
    pub ps1: PathBuf,
    pub cmd: PathBuf,
}

/// 确保两个脚本存在且内容最新（内容相同则跳过写入）。
pub fn ensure(dir: &Path) -> Result<Assets, String> {
    std::fs::create_dir_all(dir)
        .map_err(|e| format!("创建集成脚本目录 {} 失败：{e}", dir.display()))?;
    let ps1 = dir.join("scterm.ps1");
    let cmd = dir.join("scterm-cmd.cmd");
    write_if_changed(&ps1, PS1_SCRIPT)?;
    write_if_changed(&cmd, CMD_SCRIPT)?;
    Ok(Assets { ps1, cmd })
}

fn write_if_changed(path: &Path, content: &str) -> Result<(), String> {
    if let Ok(existing) = std::fs::read_to_string(path) {
        if existing == content {
            return Ok(());
        }
    }
    std::fs::write(path, content).map_err(|e| format!("写入集成脚本 {} 失败：{e}", path.display()))
}

/// 给命令行追加集成脚本的加载参数。
///
/// profile 关闭集成、程序无法识别、用户自己已经指定了 `-Command` / `/c` 时保持原样。
pub fn decorate(profile: &Profile, assets: &Assets) -> String {
    let line = profile.command_line();
    if !profile.shell_integration {
        return line;
    }
    let kind = match detect(&profile.command) {
        Some(kind) => kind,
        None => return line,
    };
    match kind {
        ShellKind::PowerShell => {
            if has_powershell_command_arg(&profile.args) {
                return line;
            }
            // Windows PowerShell 5.1 在 Server Core 上默认可能是 Restricted，
            // 只给这个进程放宽执行策略，否则集成脚本根本跑不起来。
            let policy = if is_windows_powershell(&profile.command) {
                " -ExecutionPolicy Bypass"
            } else {
                ""
            };
            format!(
                "{}{} -NoExit -Command \". '{}'\"",
                line,
                policy,
                escape_single_quoted(&assets.ps1.display().to_string())
            )
        }
        ShellKind::Cmd => {
            if has_cmd_command_arg(&profile.args) {
                return line;
            }
            format!("{} /K \"{}\"", line, assets.cmd.display())
        }
    }
}

/// 是否是 Windows PowerShell 5.1（powershell.exe），而不是 PowerShell 7（pwsh.exe）。
fn is_windows_powershell(command: &str) -> bool {
    command
        .trim_matches('"')
        .rsplit(['\\', '/'])
        .next()
        .unwrap_or(command)
        .eq_ignore_ascii_case("powershell.exe")
}

fn has_powershell_command_arg(args: &[String]) -> bool {
    args.iter().any(|arg| {
        matches!(
            arg.trim().to_ascii_lowercase().as_str(),
            "-command" | "-c" | "-file" | "-f" | "-encodedcommand" | "-e" | "-ec"
        )
    })
}

fn has_cmd_command_arg(args: &[String]) -> bool {
    args.iter().any(|arg| {
        matches!(arg.trim().to_ascii_lowercase().as_str(), "/c" | "/k")
    })
}

/// PowerShell 单引号字符串里的 `'` 要写成两个。
fn escape_single_quoted(text: &str) -> String {
    text.replace('\'', "''")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{GradientOverride, Profile};

    fn profile(command: &str, args: &[&str]) -> Profile {
        Profile {
            name: "test".to_string(),
            command: command.to_string(),
            args: args.iter().map(|s| s.to_string()).collect(),
            cwd: None,
            color_scheme: None,
            tab_color: None,
            font_face: None,
            font_size: None,
            gradient: GradientOverride::Inherit,
            gradient_top: None,
            gradient_bottom: None,
            shell_integration: true,
        }
    }

    fn assets() -> Assets {
        Assets {
            ps1: PathBuf::from(r"C:\Users\me\AppData\Local\scterm\integration\scterm.ps1"),
            cmd: PathBuf::from(r"C:\Users\me\AppData\Local\scterm\integration\scterm-cmd.cmd"),
        }
    }

    #[test]
    fn detect_shell_kinds() {
        assert_eq!(detect("pwsh.exe"), Some(ShellKind::PowerShell));
        assert_eq!(detect("PowerShell.exe"), Some(ShellKind::PowerShell));
        assert_eq!(
            detect(r#""C:\Program Files\PowerShell\7\pwsh.exe""#),
            Some(ShellKind::PowerShell)
        );
        assert_eq!(detect(r"C:/Windows/System32/cmd.exe"), Some(ShellKind::Cmd));
        assert_eq!(detect("@self"), None);
        assert_eq!(detect(r"C:\Tools\scterm.exe"), None);
        assert_eq!(detect("bash.exe"), None);
    }

    #[test]
    fn powershell_injection() {
        let p = profile("pwsh.exe", &["-NoLogo"]);
        let line = decorate(&p, &assets());
        assert!(
            line.ends_with(r#"-NoExit -Command ". 'C:\Users\me\AppData\Local\scterm\integration\scterm.ps1'""#),
            "实际：{line}"
        );

        // 用户自己指定了 -Command 时不覆盖。
        let p = profile("pwsh.exe", &["-NoLogo", "-Command", "Get-Date"]);
        assert_eq!(decorate(&p, &assets()), p.command_line());

        // 关闭集成时保持原样。
        let mut p = profile("powershell.exe", &[]);
        p.shell_integration = false;
        assert_eq!(decorate(&p, &assets()), p.command_line());
    }

    #[test]
    fn windows_powershell_relaxes_execution_policy() {
        let p = profile("powershell.exe", &["-NoLogo"]);
        let line = decorate(&p, &assets());
        assert!(line.contains("-ExecutionPolicy Bypass"), "实际：{line}");
        assert!(
            line.ends_with(r#"-NoExit -Command ". 'C:\Users\me\AppData\Local\scterm\integration\scterm.ps1'""#),
            "实际：{line}"
        );

        // PowerShell 7 不需要也不加执行策略参数。
        let p = profile("pwsh.exe", &["-NoLogo"]);
        assert!(!decorate(&p, &assets()).contains("-ExecutionPolicy"));
    }

    #[test]
    fn powershell_path_quotes_are_escaped() {
        let p = profile("pwsh.exe", &[]);
        let assets = Assets {
            ps1: PathBuf::from(r"C:\Users\O'Brien\scterm.ps1"),
            cmd: PathBuf::from(r"C:\Users\O'Brien\scterm-cmd.cmd"),
        };
        let line = decorate(&p, &assets);
        assert!(line.contains(r". 'C:\Users\O''Brien\scterm.ps1'"), "实际：{line}");
    }

    #[test]
    fn cmd_injection() {
        let p = profile("cmd.exe", &[]);
        let line = decorate(&p, &assets());
        assert!(
            line.ends_with(r#"/K "C:\Users\me\AppData\Local\scterm\integration\scterm-cmd.cmd""#),
            "实际：{line}"
        );

        // 用户自己带 /c 或 /k 时不追加。
        let p = profile("cmd.exe", &["/c", "echo hi"]);
        assert_eq!(decorate(&p, &assets()), p.command_line());
        let p = profile("cmd.exe", &["/K", "echo hi"]);
        assert_eq!(decorate(&p, &assets()), p.command_line());
    }

    #[test]
    fn scripts_carry_sequences() {
        assert!(PS1_SCRIPT.contains("]133;A"));
        assert!(PS1_SCRIPT.contains("]133;D;"));
        assert!(PS1_SCRIPT.contains("]7;file://"));
        assert!(PS1_SCRIPT.contains("__scterm_original_prompt"));
        assert!(CMD_SCRIPT.contains("]133;A"));
        assert!(CMD_SCRIPT.contains("]133;B"));
    }

    #[test]
    fn assets_written_once() {
        let dir = std::env::temp_dir().join(format!("scterm-integration-test-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        let assets = ensure(&dir).expect("写入集成脚本");
        assert_eq!(
            std::fs::read_to_string(&assets.ps1).unwrap(),
            PS1_SCRIPT
        );
        assert_eq!(
            std::fs::read_to_string(&assets.cmd).unwrap(),
            CMD_SCRIPT
        );
        // 再调用一次不应报错；文件内容保持最新。
        let again = ensure(&dir).expect("再次写入集成脚本");
        assert_eq!(std::fs::read_to_string(again.ps1).unwrap(), PS1_SCRIPT);
        let _ = std::fs::remove_dir_all(&dir);
    }
}
