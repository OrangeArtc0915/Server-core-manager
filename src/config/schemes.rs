//! 内置配色方案：Windows Terminal 官方配色 + 常用社区主题。
//!
//! 每套方案都带 16 色 ANSI 调色板（索引 0–15）。渲染层把 `Color::Indexed(0..16)`
//! 解析成这里的 RGB，所以切换主题会连 ls / git 等命令的 16 色输出一起变色。

use super::ColorScheme;
use crate::emulation::screen::Color;

fn rgb(value: u32) -> Color {
    Color::Rgb((value >> 16) as u8, (value >> 8) as u8, value as u8)
}

fn scheme(
    name: &str,
    fg: u32,
    bg: u32,
    cursor: Option<u32>,
    selection: Option<u32>,
    ansi: [u32; 16],
) -> ColorScheme {
    ColorScheme {
        name: name.to_string(),
        foreground: Some(rgb(fg)),
        background: Some(rgb(bg)),
        cursor: cursor.map(rgb),
        selection: selection.map(rgb),
        ansi: Some(ansi.map(rgb)),
    }
}

/// 用户自定义配色没写 `ansi_0..ansi_15` 时的回退值（Campbell）。
pub(super) fn fallback_ansi() -> [Color; 16] {
    [
        0x0C0C0C, 0xC50F1F, 0x13A10E, 0xC19C00, 0x0037DA, 0x881798, 0x3A96DD, 0xCCCCCC,
        0x767676, 0xE74856, 0x16C60C, 0xF9F1A5, 0x3B78FF, 0xB4009E, 0x61D6D6, 0xF2F2F2,
    ]
    .map(rgb)
}

