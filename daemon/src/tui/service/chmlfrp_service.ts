import axios from "axios";
import logger from "../../service/log";

const API = "https://cf-v2.uapis.cn";
const USER_AGENT = "CraftDock/1.0 (MCSManager Custom TUI)";

export interface ChmlTunnel {
  id: string;
  name: string;
  node: string;
  type: string;
  localIp: string;
  localPort: number;
  remotePort: string;
  online: boolean;
}

export interface ChmlNode {
  name: string;
  area: string;
  notes: string;
  group: string;
}

interface ChmlResponse {
  code?: number;
  state?: string;
  msg?: string;
  data?: any;
}

function messageOf(data: ChmlResponse): string {
  return String(data?.msg ?? data?.state ?? "ChmlFrp 请求失败");
}

/**
 * ChmlFrp v2 API client (https://docs.chmlfrp.net/API/v2/).
 *
 * ChmlFrp accepts both a user token (`token`) and an OAuth access token
 * (`access_token`) depending on how the token was obtained, so every call
 * retries with the other parameter name once.
 */
class ChmlFrpService {
  private async get(path: string, token?: string, params: Record<string, string> = {}) {
    const attempts: Record<string, string>[] = token
      ? [{ ...params, token }, { ...params, access_token: token }]
      : [params];
    let last: ChmlResponse | undefined;
    for (const query of attempts) {
      const search = new URLSearchParams(query).toString();
      const response = await axios({
        method: "GET",
        url: `${API}${path}${search ? `?${search}` : ""}`,
        timeout: 20000,
        headers: { "User-Agent": USER_AGENT }
      });
      const data = (response.data ?? {}) as ChmlResponse;
      if (data.state === "success" || data.code === 200) return data;
      last = data;
    }
    throw new Error(messageOf(last ?? {}));
  }

  private async post(path: string, body: Record<string, unknown>) {
    const response = await axios({
      method: "POST",
      url: `${API}${path}`,
      data: body,
      timeout: 20000,
      headers: { "User-Agent": USER_AGENT, "Content-Type": "application/json" }
    });
    const data = (response.data ?? {}) as ChmlResponse;
    if (data.state !== "success" && data.code !== 200) throw new Error(messageOf(data));
    return data;
  }

  async listTunnels(token: string): Promise<ChmlTunnel[]> {
    const data = await this.get("/tunnel", token);
    if (!Array.isArray(data.data)) return [];
    return data.data.map((item: any) => ({
      id: String(item.id ?? ""),
      name: String(item.name ?? ""),
      node: String(item.node ?? ""),
      type: String(item.type ?? "tcp"),
      localIp: String(item.localip ?? "127.0.0.1"),
      localPort: Number(item.nport) || 0,
      remotePort: String(item.dorp ?? ""),
      online: String(item.state ?? "").toLowerCase() === "online"
    }));
  }

  async listNodes(): Promise<ChmlNode[]> {
    const data = await this.get("/node");
    if (!Array.isArray(data.data)) return [];
    return data.data.map((item: any) => ({
      name: String(item.name ?? ""),
      area: String(item.area ?? ""),
      notes: String(item.notes ?? ""),
      group: String(item.nodegroup ?? "")
    }));
  }

  /** frpc configuration (ini text) generated by ChmlFrp for one tunnel. */
  async tunnelConfig(token: string, tunnel: { node: string; name: string }): Promise<string> {
    const data = await this.get("/tunnel_config", token, {
      node: tunnel.node,
      tunnelName: tunnel.name
    });
    const text = typeof data.data === "string" ? data.data : "";
    if (!text.trim()) throw new Error("ChmlFrp 未返回 frpc 配置");
    return text;
  }

  async createTunnel(
    token: string,
    options: {
      name: string;
      node: string;
      type: string;
      localIp: string;
      localPort: number;
      remotePort: number;
      encryption: boolean;
      compression: boolean;
    }
  ): Promise<void> {
    const body: Record<string, unknown> = {
      token,
      tunnelname: options.name,
      node: options.node,
      porttype: options.type,
      localip: options.localIp,
      localport: options.localPort,
      encryption: options.encryption,
      compression: options.compression,
      extraparams: "",
      remoteport: options.remotePort
    };
    try {
      await this.post("/create_tunnel", body);
    } catch (error) {
      // Some deployments only accept the OAuth parameter name.
      await this.post("/create_tunnel", { ...body, token: undefined, access_token: token });
    }
  }

  async removeTunnel(token: string, tunnelId: string): Promise<void> {
    await this.get("/delete_tunnel", token, { tunnelId });
  }

  /** Official ChmlFrp client bundle for this platform. */
  frpcDownloadUrl(): string {
    const arch = process.arch === "x64" ? "amd64" : process.arch;
    const platform = process.platform === "win32" ? "windows" : process.platform;
    if (process.platform === "win32") {
      return "https://cf-v1.uapis.cn/download/ChmlFrp-0.51.2_251023_2_windows_amd64.zip";
    }
    logger.warn(`[TUI] ChmlFrp frpc is only bundled for Windows (${platform}_${arch})`);
    return "https://cf-v1.uapis.cn/download/ChmlFrp-0.51.2_251023_2_windows_amd64.zip";
  }
}

export const chmlFrpService = new ChmlFrpService();
